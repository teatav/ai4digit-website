function setLang(lang) {
  const dict = I18N[lang];
  if (!dict) return;
  document.documentElement.lang = lang;
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const v = dict[el.getAttribute("data-i18n")];
    if (v != null) el.textContent = v;
  });
  document.querySelectorAll("[data-i18n-ph]").forEach(el => {
    const v = dict[el.getAttribute("data-i18n-ph")];
    if (v != null) el.setAttribute("placeholder", v);
  });
  const metaDesc = document.querySelector('meta[name="description"]');
  if (metaDesc && dict["meta.desc"]) metaDesc.setAttribute("content", dict["meta.desc"]);
  document.querySelectorAll("[data-setlang]").forEach(btn => {
    const active = btn.getAttribute("data-setlang") === lang;
    btn.classList.toggle("active", active);
    btn.setAttribute("aria-pressed", active ? "true" : "false");
  });
  try { localStorage.setItem("ai4digit-lang", lang); } catch (e) {}
}

// Language buttons
document.querySelectorAll("[data-setlang]").forEach(btn => {
  btn.addEventListener("click", () => setLang(btn.getAttribute("data-setlang")));
});

